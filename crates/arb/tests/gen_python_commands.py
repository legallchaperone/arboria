"""Write crates/arb/tests/python_commands.txt: the Python `arb` command tree, one line
per group or command, for `cli_tree.rs` to compare the Rust clap tree against.

    uv run python crates/arb/tests/gen_python_commands.py

Only reads the click tree (names, hidden flags, parameters, help panels); runs nothing.
Line format (tab separated):

    <path>  <group|command>  <visible|hidden>  <panel or ->  <params>

params, in declaration order, space separated: positional `name` (`name?` optional,
`name...` variadic), options `--flag` (boolean) or `--opt=V` (`=V...` repeatable,
`=V!` required, `=V(default)` with a non-empty default). `--help` and `--json` are left out: the Rust
CLI has one global `--json`.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import typer

from arboria import cli

OUT = Path(__file__).with_name("python_commands.txt")


def param_token(p: Any) -> str | None:
    # typer vendors click (typer._click): duck-type on param_type_name
    if p.param_type_name == "argument":
        if p.nargs == -1:
            return f"{p.name}..."
        return p.name if p.required else f"{p.name}?"
    assert p.param_type_name == "option", p
    name = sorted(p.opts, key=lambda o: (not o.startswith("--"), o))[0]
    if name in ("--help", "--json"):
        return None
    if p.is_flag:
        return name
    tok = f"{name}=V"
    if p.multiple:
        tok += "..."
    if p.required:
        tok += "!"
    if p.default is not None and p.default is not False and not callable(p.default):
        tok += f"({p.default})"
    return tok


def walk(cmd: Any, path: list[str], panel: str, lines: list[str]) -> None:
    kind = "group" if hasattr(cmd, "commands") else "command"
    vis = "hidden" if cmd.hidden else "visible"
    params = " ".join(t for p in cmd.params if (t := param_token(p)) is not None)
    lines.append("\t".join([" ".join(path), kind, vis, panel, params]).rstrip("\t"))
    if kind == "group":
        for name in sorted(cmd.commands):
            walk(cmd.commands[name], [*path, name], "-", lines)


def main() -> None:
    root = typer.main.get_command(cli.app)
    panel_of = {n: p for p, names in cli.HELP_PANELS.items() for n in names}
    lines: list[str] = []
    for name in sorted(root.commands):
        walk(root.commands[name], [name], panel_of.get(name, "-"), lines)
    header = ("# Generated by crates/arb/tests/gen_python_commands.py from the Python CLI "
              "(src/arboria/cli.py); do not edit.\n")
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
