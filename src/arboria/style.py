"""The Arboria typeface: Maple Mono CN in every notebook and in the dashboard.

The font (Regular and Bold, WOFF2, SIL OFL 1.1, `ui/fonts/OFL.txt`) ships in this
package, so every user sees the same typeface whatever is installed on their machine.
marimo inlines an app's `css_file` into the page, so a `url()` in it would be resolved
against the server and could not reach a file next to the notebook; the fonts therefore
go into the stylesheet itself as `data:` URIs. No request leaves the page: offline.

- Notebooks: `arboria.css` next to each notebook (`.arboria/notebooks/`, linked into the
  idea's worktree like `notebook.py`; `<home>/seeds/`), and `App(css_file="arboria.css")`
  in the notebook. The backup repo only versions `*.py`, so the font never lands there.
- Dashboard: `arb ui` runs marimo on a link to the packaged app in `<cache>/ui/`, next
  to a `dashboard.css` that carries the font (`dashboard_app`); the packaged
  `ui/dashboard.css` itself stays font-free, so the standalone HTML of `views.page`
  falls back to system fonts.

Every file here is generated: `ensure` rewrites it only when its content would change
(the first line carries a digest), so repeated calls are cheap.
"""

from __future__ import annotations

import base64
import functools
import hashlib
import os
from pathlib import Path

from .paths import cache_dir

UI_DIR = Path(__file__).with_name("ui")
FONTS_DIR = UI_DIR / "fonts"
FONT_FAMILY = "Maple Mono CN"
FONT_VERSION = "v7.9"
FONT_FILES = (("MapleMono-CN-Regular.woff2", 400), ("MapleMono-CN-Bold.woff2", 700))
LICENSE_FILE = FONTS_DIR / "OFL.txt"
NOTEBOOK_CSS = UI_DIR / "notebook.css"
DASHBOARD_CSS = UI_DIR / "dashboard.css"
# what notebooks name in App(css_file=...): a file next to the notebook
STYLE_NAME = "arboria.css"
MARK = "/* arboria-style "


@functools.cache
def font_face() -> str:
    """The @font-face rules of the packaged font, with the files as data: URIs."""
    rules = []
    for name, weight in FONT_FILES:
        data = base64.b64encode((FONTS_DIR / name).read_bytes()).decode("ascii")
        rules.append(
            f'@font-face {{ font-family: "{FONT_FAMILY}"; font-style: normal; '
            f"font-weight: {weight}; font-display: block; "
            f'src: url("data:font/woff2;base64,{data}") format("woff2"); }}')
    return "\n".join(rules)


def stylesheet(*sources: Path) -> str:
    """The font's @font-face rules followed by the given stylesheets, behind a header
    line with a digest of everything (what `ensure` compares)."""
    body = font_face() + "\n\n" + "\n".join(p.read_text(encoding="utf-8") for p in sources)
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]
    header = (f"{MARK}{digest} */\n"
              f"/* Generated by arb; edits are overwritten. Font: {FONT_FAMILY} {FONT_VERSION} "
              f"(SIL Open Font License 1.1, https://github.com/subframe7536/maple-font), "
              f"embedded below as data: URIs. */\n")
    return header + body


def _first_line(path: Path) -> str:
    try:
        with path.open("r", encoding="utf-8") as f:
            return f.readline()
    except (OSError, UnicodeDecodeError):
        return ""


def ensure(path: Path, *sources: Path) -> bool:
    """Write `stylesheet(*sources)` to `path` unless it is already there (atomic).
    True if written."""
    text = stylesheet(*sources)
    if _first_line(path) == text.partition("\n")[0] + "\n":
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.arboria-tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
    return True


def ensure_notebook_style(directory: Path) -> Path:
    """`<directory>/arboria.css`, the stylesheet the notebooks there name."""
    path = Path(directory) / STYLE_NAME
    ensure(path, NOTEBOOK_CSS)
    return path


def link(link_path: Path, target: Path) -> bool:
    """Make `link_path` a symlink to `target` (replacing a stale symlink, never a file).
    True if `link_path` now points at `target`."""
    if link_path.is_symlink():
        if os.readlink(link_path) == str(target):
            return True
        link_path.unlink()
    elif link_path.exists():
        return False
    link_path.symlink_to(target)
    return True


def dashboard_app(app: Path) -> Path:
    """The dashboard (or garden) app to hand to `marimo run`: a link to the packaged
    `app` in `<cache>/ui/`, next to a `dashboard.css` that carries the font. marimo
    reads `css_file` relative to the path it was given (it does not resolve links). If
    the cache cannot be written, the packaged app itself (system fonts)."""
    try:
        ui = cache_dir() / "ui"
        ensure(ui / DASHBOARD_CSS.name, NOTEBOOK_CSS, DASHBOARD_CSS)
        target = ui / app.name
        if not link(target, app):
            return app
        return target
    except OSError:
        return app
