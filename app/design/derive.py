"""Derive the app's stylesheets from the design system's tokens.css (see README.md).

python3 derive.py OUT_DIR  ->  OUT_DIR/tokens.css, OUT_DIR/ab-tokens.css
"""
import re
import sys
from pathlib import Path

src = (Path(__file__).parent / "tokens.css").read_text()
out = Path(sys.argv[1])


def block(selector: str) -> str:
    m = re.search(re.escape(selector) + r"\s*\{(.*?)\n\}", src, re.S)
    if not m:
        raise SystemExit(f"tokens.css: no block {selector!r}")
    return m.group(1).strip("\n")


light = block(':root, [data-theme="light"]')
dark = block('[data-theme="dark"]')
sizes = re.search(r"\n:root \{(\n  --space-1.*?)\n\}", src, re.S).group(1)
rest = src[src.index(".title {"):]
rest = rest.replace('url("fonts/', 'url("arboria://fonts/')

tokens = (
    "/* Generated by app/design/derive.py from the design system's tokens.css. */\n"
    f":root {{\n{light}\n}}\n"
    f"@media (prefers-color-scheme: dark) {{\n  :root {{\n{dark}\n  }}\n}}\n"
    f":root {{{sizes}\n}}\n{rest}"
)
(out / "tokens.css").write_text(tokens)


def prefixed(body: str) -> str:
    return re.sub(r"--([a-z][a-z0-9-]*)", r"--ab-\1", body)


ab = (
    "/* Generated by app/design/derive.py: the design tokens as --ab-* for the marimo page. */\n"
    f":root {{\n{prefixed(light)}\n}}\n"
    f"@media (prefers-color-scheme: dark) {{\n  :root {{\n{prefixed(dark)}\n  }}\n}}\n"
    f":root {{{prefixed(sizes)}\n}}\n"
    + "\n".join(l for l in rest.splitlines() if l.startswith("@font-face")) + "\n"
)
(out / "ab-tokens.css").write_text(ab)
